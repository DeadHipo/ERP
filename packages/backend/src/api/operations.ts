/** A write needs `X-Operator` unless it is public (login, logout: D-170). */
export const needsOperator = (o: Pick<ApiOperation, 'method' | 'access'>) => o.method !== 'get' && o.access !== 'public';

/**
 * Every write (post, patch) that is not public declares the `X-Operator` header (D-140, D-170); every `org` operation
 * declares the optional `X-Org` of the system administrator.
 */
export const API_OPERATIONS: ApiOperation[] = operations.map((o) => {
  const headers = [
    ...(needsOperator(o) ? [OPERATOR_HEADER] : []),
    ...(o.access === 'org' ? [ORG_HEADER] : []),
    ...(o.headers ?? []),
  ];
  return headers.length ? { ...o, headers } : o;
});

export const operationKey = (o: Pick<ApiOperation, 'method' | 'path'>) =>
  `${o.method.toUpperCase()} ${o.path}`;

/**
 * The operations whose `labelId` in the body is the target of a move between books, not the label the request acts
 * under (D-171 plan §2 rule (b)): their scope is not `label`.
 */
export const RELABEL_OPERATIONS: ReadonlySet<string> = new Set([
  'PATCH /documents/:id',
  'PATCH /settlements/operations/:id',
  'PATCH /ads/:id',
]);

interface Matcher {
  op: ApiOperation;
  method: string;
  /** Static segments in lower case; null = a parameter. */
  segments: (string | null)[];
}

const MATCHERS: Matcher[] = API_OPERATIONS.map((op) => ({
  op,
  method: op.method.toUpperCase(),
  segments: op.path
    .split('/')
    .slice(1)
    .map((s) => (s.startsWith(':') ? null : s.toLowerCase())),
}));

/** -1 when `a` is the more specific (a static segment where `b` has a parameter, first difference from the left). */
function bySpecificity(a: Matcher, b: Matcher): number {
  for (let i = 0; i < a.segments.length; i++) {
    const sa = a.segments[i] !== null;
    const sb = b.segments[i] !== null;
    if (sa !== sb) return sa ? -1 : 1;
  }
  return 0;
}

/**
 * The operation a request reaches (D-171), matched like the Express 5 router does (`caseSensitive: false`,
 * `strict: false`): the method in upper case (HEAD = GET), one trailing `/` dropped, static segments compared in lower
 * case, a parameter is one non-empty segment; a static segment beats a parameter (`/owners/payables` before
 * `/owners/:id`, as the routes are registered). `path` is relative to /api/v1. Undefined = no operation.
 */
export function operationOf(method: string, path: string): ApiOperation | undefined {
  const m = method.toUpperCase() === 'HEAD' ? 'GET' : method.toUpperCase();
  const p = path.length > 1 && path.endsWith('/') ? path.slice(0, -1) : path;
  if (!p.startsWith('/')) return undefined;
  const segs = p.split('/').slice(1);
  const found = MATCHERS.filter(
    (x) =>
      x.method === m &&
      x.segments.length === segs.length &&
      x.segments.every((s, i) => {
        const seg = segs[i] as string;
        return s === null ? seg !== '' : seg.toLowerCase() === s;
      }),
  ).sort(bySpecificity);
  return found[0]?.op;
}

/** An operation of an organization (its `ability` has a scope). */
export type OrgOperation = ApiOperation & { access: 'org'; ability: Ability };
export const isOrgOperation = (o: ApiOperation): o is OrgOperation => o.access === 'org';
