// The API contract as data: one entry per route of /api/v1. The OpenAPI document is built from it, and the tests
// check that it matches the routes Express really has and that real responses fit the response schemas.

export type HttpMethod = 'get' | 'post' | 'patch';

interface OperationBase {
  method: HttpMethod;
  /** Express style (`/owners/:id`). */
  path: string;
  tag: string;
  summary: string;
  query?: z.ZodObject;
  body?: z.ZodType;
  /** Multipart upload with a single `file` part. */
  upload?: boolean;
  /**
   * A write with a preview mode (`dryRun` in its query, D-172): the preview answers 200 and leaves no audit row. Read
   * only by the contract test; the audit hook knows the route from `RESPONSE_SUMMARY_ROUTES`.
   */
  preview?: boolean;
  /** Success status (default 200). */
  status?: 200 | 201;
  /**
   * D-173: with `format=csv` the operation answers `text/csv` (UTF-8 with BOM) instead of `response`: OpenAPI gives a
   * second content, the contract test calls both and checks the csv header.
   */
  csv?: true;
  response: z.ZodType;
  /**
   * Who may call it (D-170): `public` without a session; `user` any session, no organization (`/auth/me`); `system` a
   * system administrator's session or `X-System-Key`; `org` the organization of the session (or `X-Org` of the system
   * administrator). `X-Operator` is required on every write whose access is not `public`.
   */
  access: 'public' | 'user' | 'system' | 'org';
  /** Request headers the operation reads (`X-Operator` on every write, D-140; `X-Org` on `org`). */
  headers?: { name: string; required: boolean; description: string }[];
  /** Error codes worth knowing, as `status code: meaning`. */
  errors?: string[];
  /** D-178: the money answers: the meaning of the response fields goes into the description, for Claude and the docs. */
  explain?: true;
}

/**
 * Every operation that is not public carries the right it needs (D-171, `auth/abilities.ts`): `action`, `subject`
 * and, on the operations of an organization, one `scope` (`label` / `record` / `org`). `access` still decides the
 * chain (who is authenticated, which router); `ability` decides the right.
 */
export type ApiOperation = OperationBase &
  ({ access: 'public'; ability?: undefined } | { access: 'user' | 'system' | 'org'; ability: Ability });

